def generate_variations(base_questions, tool_name, tool_args):
    """기본 질문에서 접미사/접두사 조합으로 변형 생성"""
    results = []
    seen = set()

    for q in base_questions:
        # 원본
        if q not in seen:
            results.append((q, tool_name, tool_args))
            seen.add(q)

        # 접미사 조합
        for suffix in SUFFIXES:
            variant = f"{q} {suffix}"
            if variant not in seen:
                results.append((variant, tool_name, tool_args))
                seen.add(variant)

        # 접두사 조합 (일부만)
        for prefix in PREFIXES[:4]:  # 지금, 현재, 오늘, 이번달
            variant = f"{prefix} {q}"
            if variant not in seen:
                results.append((variant, tool_name, tool_args))
                seen.add(variant)

        # 접두사+접미사 조합 (일부)
        for prefix in PREFIXES[:2]:
            for suffix in SUFFIXES[:5]:
                variant = f"{prefix} {q} {suffix}"
                if variant not in seen:
                    results.append((variant, tool_name, tool_args))
                    seen.add(variant)

    return results


def generate_all():
    """전체 패턴 생성"""
    all_patterns = []

    for tool_name, tool_args, base_questions in PATTERNS:
        variations = generate_variations(base_questions, tool_name, tool_args)
        all_patterns.extend(variations)

    return all_patterns


def generate_sql(patterns):
    """INSERT SQL 생성"""
    lines = [
        "-- ══════════════════════════════════════════════",
        "-- MCP 질문 패턴 시드 데이터 (자동 생성)",
        f"-- 총 {len(patterns)}개 패턴",
        "-- ══════════════════════════════════════════════",
        "",
        "-- 기존 시드 데이터 정리 (hit_count=0인 것만)",
        "DELETE FROM light_sync.mcp_query_patterns WHERE hit_count <= 1 AND created_at < NOW() - INTERVAL '1 day';",
        "",
        "INSERT INTO light_sync.mcp_query_patterns (question, tool_name, tool_args, success, hit_count)",
        "VALUES",
    ]

    value_lines = []
    for question, tool_name, tool_args in patterns:
        q_escaped = question.replace("'", "''")
        args_json = json.dumps(tool_args, ensure_ascii=False).replace("'", "''")
        value_lines.append(
            f"  ('{q_escaped}', '{tool_name}', '{args_json}'::jsonb, true, 1)"
        )

    lines.append(",\n".join(value_lines))
    lines.append("ON CONFLICT DO NOTHING;")
    lines.append("")

    return "\n".join(lines)


